export const french: LanguagePack = {
  id: "fr",
  name: "Français",
  dateOrder: "DMY",
  normalize(input) {
    let text = europeanClock(input.normalize("NFC").toLowerCase());
    text = text.replace(
      /\b(lundi|mardi|mercredi|jeudi|vendredi|samedi|dimanche) prochain\b/g,
      "prochain $1",
    );
    text = replaceWords(text, words);
    text = text.replace(
      /\bat (\d{1,2}|one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve) hours?\b/g,
      "at $1",
    );
    text = text.replace(
      /\b(last|first|second|third|fourth) (monday|tuesday|wednesday|thursday|friday|saturday|sunday) from (every|the) month\b/g,
      "the $1 $2 of each month",
    );
    text = text.replace(
      /\bfrom (\d{1,2}:\d{2}) at (\d{1,2}:\d{2})\b/g,
      "from $1 to $2",
    );
    return validateEnglish(text);
  },
};
