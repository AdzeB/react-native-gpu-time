export const spanish: LanguagePack = {
  id: "es",
  name: "Español",
  dateOrder: "DMY",
  normalize(input) {
    let text = europeanClock(input.normalize("NFC").toLowerCase());
    text = text.replace(
      /\b(lunes|martes|miércoles|jueves|viernes|sábado|domingo) próximo\b/g,
      "próximo $1",
    );
    text = replaceWords(text, words);
    // Spanish month dates contain 'de'; English month dates do not.
    text = text.replace(
      /\b(\d{1,2}) of (january|february|march|april|may|june|july|august|september|october|november|december)\b/g,
      "$1 $2",
    );
    text = text.replace(
      /\b(january|february|march|april|may|june|july|august|september|october|november|december) of (\d{4})\b/g,
      "$1 $2",
    );
    text = text.replace(
      /\bat (\d{1,2}|one|two|three|four|five|six|seven|eight|nine|ten|eleven|twelve) hours?\b/g,
      "at $1",
    );
    text = text.replace(
      /\bof (\d{1,2}:\d{2}) to (\d{1,2}:\d{2})\b/g,
      "from $1 to $2",
    );
    return validateEnglish(text);
  },
};
